export type DemoFormFieldKind =
  "text" | "email" | "date" | "number" | "select" | "textarea" | "file";

export interface DemoFormField {
  section: string;
  id: string;
  label: string;
  kind: DemoFormFieldKind;
  required: boolean;
  sampleValue: string;
  options?: string[];
  helpText?: string;
  disabled?: boolean;
}

export interface DemoFormProfile {
  title: string;
  description: string;
  fields: DemoFormField[];
  note: string;
}

function field(
  section: string,
  id: string,
  label: string,
  kind: DemoFormFieldKind,
  sampleValue: string,
  required = true,
  helpText?: string,
  options?: string[],
  disabled = false,
): DemoFormField {
  return {
    section,
    id,
    label,
    kind,
    sampleValue,
    required,
    helpText,
    options,
    disabled,
  };
}

const text = (
  section: string,
  id: string,
  label: string,
  value: string,
  required = true,
  helpText?: string,
) => field(section, id, label, "text", value, required, helpText);

const date = (section: string, id: string, label: string, value: string) =>
  field(section, id, label, "date", value);

const number = (
  section: string,
  id: string,
  label: string,
  value: string,
  helpText?: string,
) => field(section, id, label, "number", value, true, helpText);

const select = (
  section: string,
  id: string,
  label: string,
  options: string[],
  value: string,
  required = true,
) => field(section, id, label, "select", value, required, undefined, options);

const textarea = (
  section: string,
  id: string,
  label: string,
  value: string,
  required = true,
  helpText?: string,
) => field(section, id, label, "textarea", value, required, helpText);

const form = (
  title: string,
  description: string,
  fields: DemoFormField[],
  note: string,
): DemoFormProfile => ({ title, description, fields, note });

