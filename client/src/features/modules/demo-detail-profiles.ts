export type DemoDetailLayout =
  | "asset"
  | "workflow"
  | "catalog"
  | "comparison"
  | "communication"
  | "procurement"
  | "service"
  | "master"
  | "report"
  | "self-service";

export interface DemoDetailProfile {
  entityType: string;
  layout: DemoDetailLayout;
  summary: string;
  overviewTab: string;
  detailTab: string;
  activityTab: string;
  overviewColumns: number[];
  detailColumns: number[];
  ownerLabel: string;
  ownerColumn: number | null;
  relatedTitle: string;
  relatedColumns: number[];
  railTitle: string;
  railNote: string;
}

function profile(
  entityType: string,
  layout: DemoDetailLayout,
  summary: string,
  detailTab: string,
  overviewColumns: number[],
  detailColumns: number[],
  ownerLabel: string,
  ownerColumn: number | null,
  relatedTitle: string,
  relatedColumns: number[],
  railTitle: string,
  railNote: string,
): DemoDetailProfile {
  return {
    entityType,
    layout,
    summary,
    overviewTab: "Overview",
    detailTab,
    activityTab: `${entityType} history`,
    overviewColumns,
    detailColumns,
    ownerLabel,
    ownerColumn,
    relatedTitle,
    relatedColumns,
    railTitle,
    railNote,
  };
}

